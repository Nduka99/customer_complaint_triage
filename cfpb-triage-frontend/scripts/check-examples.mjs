// Checks every example complaint against the live backend, twice each, so the app's labels match
// what the deployed model does. An "escalate" example must be sent to a person by a confidence
// gate; an "automatic" example must clear both gates. (Above the gates the route is a random
// draw, so it is never relied on.)
//
//   node scripts/check-examples.mjs                   check only (exit 1 on any mismatch)
//   node scripts/check-examples.mjs --write-samples   also rewrite src/cachedExample.js
import { writeFileSync } from "node:fs";
import { EXAMPLES } from "../src/examples.js";

const SPACE = "https://nduka1999-cfpb-triage-backend.hf.space";
const RUNS = 2;

// Same two calls as the keep-alive workflow: start a job, then read its result stream.
async function classify(text) {
  const start = await fetch(`${SPACE}/gradio_api/call/classify`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ data: [text] }),
  });
  if (!start.ok) throw new Error(`backend returned ${start.status}`);
  const { event_id: eventId } = await start.json();
  const stream = await (await fetch(`${SPACE}/gradio_api/call/classify/${eventId}`)).text();
  const line = stream.split("\n").find((row) => row.startsWith("data:") && row.includes("{"));
  if (!line) throw new Error(`no result in stream: ${stream.slice(0, 200)}`);
  return JSON.parse(line.slice("data:".length))[0];
}

// Which confidence gate (if any) sent the complaint to a person, read from the backend's reason.
function gateOf(result) {
  const reason = result.routing?.reason ?? "";
  if (reason.includes("early-exit")) return "first-model confidence below 0.65";
  if (reason.includes("below 0.55")) return "final confidence below 0.55";
  return null;
}

let failures = 0;
const firstResult = new Map();
for (const example of EXAMPLES) {
  for (let run = 1; run <= RUNS; run++) {
    const result = await classify(example.text);
    const gate = gateOf(result);
    const ok = example.expect === "escalate" ? gate !== null : gate === null;
    if (!ok) failures++;
    if (!firstResult.has(example.label)) firstResult.set(example.label, result);
    console.log(
      `${ok ? "ok  " : "FAIL"} ${example.label} (run ${run}, expect ${example.expect}): ` +
        `${result.routing?.decision}; ${gate ?? "no gate"}; ${result.summary}`,
    );
  }
}

if (process.argv.includes("--write-samples")) {
  if (failures > 0) {
    console.error("Samples not written: fix the failing examples first.");
  } else {
    const automatic = EXAMPLES.find((example) => example.expect === "automatic");
    const escalate = EXAMPLES.find((example) => example.expect === "escalate");
    const file = [
      "// Generated by scripts/check-examples.mjs --write-samples from live backend responses.",
      `// Recorded ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: re-run the script.`,
      "// Shown, marked as stored results, while the backend wakes from sleep.",
      "",
      `export const CACHED_EXAMPLE_LABEL = ${JSON.stringify(automatic.label)};`,
      `export const CACHED_EXAMPLE = ${JSON.stringify(firstResult.get(automatic.label), null, 2)};`,
      "",
      `export const CACHED_ESCALATION_LABEL = ${JSON.stringify(escalate.label)};`,
      `export const CACHED_ESCALATION = ${JSON.stringify(firstResult.get(escalate.label), null, 2)};`,
      "",
    ].join("\n");
    writeFileSync(new URL("../src/cachedExample.js", import.meta.url), file);
    console.log("Wrote src/cachedExample.js");
  }
}

console.log(failures ? `${failures} mismatch(es)` : "All example labels match the live model.");
process.exit(failures ? 1 : 0);
